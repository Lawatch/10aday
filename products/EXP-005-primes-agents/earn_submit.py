#!/usr/bin/env python3
"""earn_submit — vérifie puis (sur ordre explicite) envoie une participation Superteam Earn (EXP-005).

Par défaut : AUCUN envoi. Le script vérifie le brouillon et affiche ce qui partirait.
L'envoi réel exige `--send --yes` ET une clé agent qui marche (proxy ou EARN_API_KEY).

Brouillon = fichier JSON dans le dépôt (sans secret ni donnée perso) :
  {
    "listingId": "…",            # id de l'annonce (champ `id` de /api/agents/listings/live)
    "slug": "…",                 # pour relire le détail de l'annonce (questions, type)
    "link": "https://github.com/Lawatch/10aday/tree/main/products/EXP-005-primes-agents/<slug>",
    "otherInfo": "… Réalisé par des agents IA (système 10aday) …",
    "eligibilityAnswers": [{"question": "…", "answer": "…"}],
    "ask": null                  # montant demandé si compensationType = range/variable
  }
Le Telegram de l'humain (obligatoire pour les annonces `project`) n'est JAMAIS dans le dépôt :
il est lu dans la variable d'environnement EARN_TELEGRAM au moment de l'envoi.

Champs de l'API vérifiés dans SuperteamDAO/earn, src/pages/api/agents/submissions/create.ts
(lu le 2026-11-12) : listingId, link, tweet, otherInfo, eligibilityAnswers, ask, telegram.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from urllib.parse import quote

BASE = os.environ.get("EARN_BASE_URL", "https://superteam.fun")
AI_MARKERS = ("agent ia", "agents ia", "ai agent", "ai-generated", "generated by ai",
              "produced by ai", "made by ai", "by an ai")
REPO_PREFIX = "https://github.com/Lawatch/10aday"


def check(draft: dict, details: dict | None = None) -> list[str]:
    """Renvoie la liste des problèmes (vide = prêt)."""
    errs: list[str] = []
    if not draft.get("listingId"):
        errs.append("listingId manquant")
    link = draft.get("link") or ""
    if not link.startswith("https://"):
        errs.append("link doit être une URL https")
    elif not link.startswith(REPO_PREFIX):
        errs.append("link hors du dépôt 10aday (le livrable doit y être publié et testé)")
    info = (draft.get("otherInfo") or "").lower()
    if not any(m in info for m in AI_MARKERS):
        errs.append("otherInfo doit dire que le travail est fait par des agents IA (charte, règle 7)")
    for k in ("privateKey", "secretKey", "seed", "mnemonic", "apiKey", "claimCode", "telegram"):
        if k in draft:
            errs.append(f"champ interdit dans le brouillon : {k} (secret ou donnée perso)")
    answers = draft.get("eligibilityAnswers") or []
    for i, a in enumerate(answers):
        if not str(a.get("question", "")).strip() or not str(a.get("answer", "")).strip():
            errs.append(f"réponse d'éligibilité n°{i + 1} vide")
    if details:
        qs = [q.get("question") for q in (details.get("eligibility") or []) if q.get("question")]
        got = {str(a.get("question", "")).strip() for a in answers}
        for q in qs:
            if q.strip() not in got:
                errs.append(f"question sans réponse : {q}")
        if details.get("type") == "project" and not os.environ.get("EARN_TELEGRAM"):
            errs.append("annonce de type project : Telegram de l'humain requis (EARN_TELEGRAM) → demande humaine")
        ct = details.get("compensationType")
        if ct in ("range", "variable"):
            ask = draft.get("ask")
            if not isinstance(ask, (int, float)) or ask <= 0:
                errs.append(f"compensationType={ct} : montant `ask` requis")
            elif ct == "range":
                lo, hi = details.get("minRewardAsk"), details.get("maxRewardAsk")
                if (lo is not None and ask < lo) or (hi is not None and ask > hi):
                    errs.append(f"ask={ask} hors de la fourchette {lo}-{hi}")
        if details.get("status") not in (None, "OPEN"):
            errs.append(f"annonce non ouverte (status={details.get('status')})")
    return errs


def payload(draft: dict) -> dict:
    p = {k: draft.get(k) for k in ("listingId", "link", "otherInfo", "eligibilityAnswers", "ask")}
    p["tweet"] = ""
    p["eligibilityAnswers"] = p["eligibilityAnswers"] or []
    tg = os.environ.get("EARN_TELEGRAM")
    if tg:
        p["telegram"] = tg
    return p


def _req(method: str, path: str, body: dict | None = None):
    key = os.environ.get("EARN_API_KEY") or "sk_injected_by_proxy"
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(f"{BASE}{path}", data=data, method=method, headers={
        "User-Agent": "earn-submit/1.0", "Authorization": f"Bearer {key}",
        "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("draft")
    ap.add_argument("--details", help="JSON du détail de l'annonce (hors ligne)")
    ap.add_argument("--fetch-details", action="store_true", help="lire le détail via l'API agents")
    ap.add_argument("--send", action="store_true")
    ap.add_argument("--yes", action="store_true", help="confirmation obligatoire avec --send")
    a = ap.parse_args(argv)

    with open(a.draft, encoding="utf-8") as f:
        draft = json.load(f)
    details = None
    try:
        if a.details:
            with open(a.details, encoding="utf-8") as f:
                details = json.load(f)
        elif a.fetch_details and draft.get("slug"):
            details = _req("GET", f"/api/agents/listings/details/{quote(draft['slug'])}")
    except urllib.error.HTTPError as e:
        sys.stderr.write(f"Détail illisible : HTTP {e.code} (401 = clé refusée, voir HQ-011).\n")
        return 2

    errs = check(draft, details)
    if errs:
        sys.stdout.write("PAS PRÊT :\n" + "".join(f"- {e}\n" for e in errs))
        return 1
    p = payload(draft)
    shown = dict(p, telegram="<masqué>") if "telegram" in p else p
    sys.stdout.write("PRÊT. Envoi prévu :\n" + json.dumps(shown, ensure_ascii=False, indent=2) + "\n")
    if not a.send:
        sys.stdout.write("(simulation : rien n'est envoyé ; ajouter --send --yes)\n")
        return 0
    if not a.yes:
        sys.stderr.write("--send exige --yes.\n")
        return 1
    try:
        res = _req("POST", "/api/agents/submissions/create", p)
    except urllib.error.HTTPError as e:
        sys.stderr.write(f"Envoi refusé : HTTP {e.code} {e.read()[:300]!r}\n")
        return 2
    sys.stdout.write("ENVOYÉ. id de participation : " + str(res.get("id")) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
